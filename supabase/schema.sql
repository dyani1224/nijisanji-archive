-- 니지산지 아카이브: Supabase 에서 SQL Editor 에 붙여 넣고 Run 을 한 번 누른다.
-- 여러 번 실행해도 안전하도록 IF NOT EXISTS 로 썼다.

create table if not exists public.livers (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  channel_id text not null,
  name text not null,
  avatar text not null default '',
  last_fetched timestamptz,
  created_at timestamptz not null default now(),
  unique (user_id, channel_id)
);

create table if not exists public.videos (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  liver_id bigint not null references public.livers(id) on delete cascade,
  youtube_id text not null,
  title text not null,
  published_at timestamptz not null,
  duration integer not null default 0,
  live_status text not null default 'none',
  category text not null default 'other' check (category in ('cover', 'karaoke', 'live', 'other')),
  category_manual boolean not null default false,
  favorite boolean not null default false,
  memo text not null default '',
  created_at timestamptz not null default now(),
  unique (user_id, youtube_id)
);
create index if not exists videos_liver_idx on public.videos (liver_id, published_at desc);
create index if not exists videos_pub_idx on public.videos (user_id, published_at desc);

create table if not exists public.timestamps (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  video_id bigint not null references public.videos(id) on delete cascade,
  seconds integer not null check (seconds >= 0),
  note text not null default '',
  created_at timestamptz not null default now()
);
create index if not exists timestamps_video_idx on public.timestamps (video_id, seconds);

-- 내 기록은 로그인한 내 계정만 읽고 쓸 수 있다.
alter table public.livers enable row level security;
alter table public.videos enable row level security;
alter table public.timestamps enable row level security;

drop policy if exists "own livers" on public.livers;
create policy "own livers" on public.livers for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

drop policy if exists "own videos" on public.videos;
create policy "own videos" on public.videos for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

drop policy if exists "own timestamps" on public.timestamps;
create policy "own timestamps" on public.timestamps for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

-- 계정 만들기 차단: 아래 이메일 한 개만 가입을 허용한다. 'you@example.com' 을 본인 이메일로 바꾼 뒤 Run.
create or replace function public.only_owner_can_sign_up()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if lower(new.email) <> lower('you@example.com') then
    raise exception 'sign-up is closed';
  end if;
  return new;
end $$;

drop trigger if exists only_owner_sign_up on auth.users;
create trigger only_owner_sign_up before insert on auth.users
  for each row execute function public.only_owner_can_sign_up();
